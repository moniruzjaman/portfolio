/**
 * gen-static.mjs — writes the files that must agree with the deployment base path:
 *   public/404.html   GitHub Pages deep-link shim (needs the base to match)
 *   public/sitemap.xml, public/robots.txt   (need the absolute site URL)
 *
 * They used to be hand-written with "/portfolio/" and the site root baked in, which
 * disagreed with each other. Deriving all three from BASE_PATH / SITE_ORIGIN — the
 * same inputs vite.config.ts reads — removes that class of drift.
 */
import { readFileSync, writeFileSync } from "node:fs";

const BASE = process.env.BASE_PATH || "/portfolio/";
const ORIGIN = (process.env.SITE_ORIGIN || "https://moniruzjaman.github.io").replace(/\/$/, "");
const SITE = `${ORIGIN}${BASE}`;

const repos = JSON.parse(readFileSync("src/data/repos.generated.json", "utf8")).repos;
// Registered notes only: the registry, not the directory, defines what is
// published — unregistered template case studies live in the same folder and
// must not appear in the sitemap (scripts/prerender.mjs cross-checks this).
const registry = readFileSync("src/content/notes.ts", "utf8");
const noteSlugs = [...registry.matchAll(/from "\.\/notes\/([A-Za-z0-9_-]+)"/g)]
  .map((m) => readFileSync(`src/content/notes/${m[1]}.ts`, "utf8").match(/slug:\s*"([^"]+)"/)?.[1])
  .filter(Boolean);

const paths = [
  "",
  "works",
  "topics",
  "library",
  "expertise",
  "notes",
  "about",
  ...repos.map((r) => `works/${r.slug}`),
  ...noteSlugs.map((s) => `notes/${s}`),
];
// lastmod = build date. Notes and repos change via sync, so the build date is the
// honest "this URL was last (re)generated" signal for both.
const LASTMOD = new Date().toISOString().slice(0, 10);
// Both languages, cross-linked: each <url> carries xhtml:link alternates so
// crawlers treat /bn/… as the Bangla variant of the English page, not as
// separate content. Locs must match canonicalForLang in src/lib/seo.ts and
// hrefFor in src/lib/lang-url.ts — prerender.mjs asserts the agreement.
const root = SITE.replace(/\/$/, "");
const loc = (lang, p) =>
  p === "" ? (lang === "bn" ? `${root}/bn` : SITE) : `${root}${lang === "bn" ? "/bn" : ""}/${p}`;
const altTags = (p) =>
  ["en", "bn", "x-default"]
    .map((h) => {
      const lang = h === "x-default" ? "en" : h;
      return `    <xhtml:link rel="alternate" hreflang="${h}" href="${loc(lang, p)}"/>`;
    })
    .join("\n");
writeFileSync(
  "public/sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n` +
    paths
      .flatMap((p) =>
        ["en", "bn"].map(
          (lang) =>
            `  <url><loc>${loc(lang, p)}</loc><lastmod>${LASTMOD}</lastmod>\n${altTags(p)}\n  </url>`,
        ),
      )
      .join("\n") +
    `\n</urlset>\n`,
);

writeFileSync("public/robots.txt", `User-agent: *\nAllow: /\n\nSitemap: ${SITE}sitemap.xml\n`);

writeFileSync(
  "public/404.html",
  `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>Abu Md. Moniruzjaman</title>
    <meta name="robots" content="noindex" />
    <script>
      /* GENERATED by scripts/gen-static.mjs — do not edit.
       * GitHub Pages has no rewrites, so a cold load of a deep link would 404 before
       * the SPA boots. Stash the path, bounce to the shell; src/main.tsx replays it. */
      (function () {
        var BASE = ${JSON.stringify(BASE)};
        var p = window.location.pathname;
        if (p.indexOf(BASE) === 0 && p !== BASE) {
          try { sessionStorage.setItem("ph:redirect", p + window.location.search + window.location.hash); } catch (e) {}
          window.location.replace(BASE + "index.html");
        }
      })();
    </script>
  </head>
  <body></body>
</html>
`,
);
console.log(`static: base ${BASE} · ${(paths.length * 2)} sitemap URLs (en + bn) · ${SITE}`);
