/**
 * gen-static.mjs — writes the files that must agree with the deployment base path:
 *   public/404.html   GitHub Pages deep-link shim (needs the base to match)
 *   public/sitemap.xml, public/robots.txt   (need the absolute site URL)
 *
 * They used to be hand-written with "/portfolio/" and the site root baked in, which
 * disagreed with each other. Deriving all three from BASE_PATH / SITE_ORIGIN — the
 * same inputs vite.config.ts reads — removes that class of drift.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const BASE = process.env.BASE_PATH || "/portfolio/";
const ORIGIN = (process.env.SITE_ORIGIN || "https://moniruzjaman.github.io").replace(/\/$/, "");
const SITE = `${ORIGIN}${BASE}`;

const repos = JSON.parse(readFileSync("src/data/repos.generated.json", "utf8")).repos;
const noteSlugs = readdirSync("src/content/notes")
  .filter((f) => f.endsWith(".ts"))
  .map((f) => readFileSync(`src/content/notes/${f}`, "utf8").match(/slug:\s*"([^"]+)"/)?.[1])
  .filter(Boolean);

const paths = [
  "", "works", "library", "expertise", "notes", "about",
  ...repos.map((r) => `works/${r.slug}`),
  ...noteSlugs.map((s) => `notes/${s}`),
];
writeFileSync(
  "public/sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    paths.map((p) => `  <url><loc>${SITE}${p}</loc></url>`).join("\n") +
    `\n</urlset>\n`,
);

writeFileSync("public/robots.txt", `User-agent: *\nAllow: /\n\nSitemap: ${SITE}sitemap.xml\n`);

writeFileSync(
  "public/404.html",
  `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>Abu Md. Moniruzzaman</title>
    <script>
      /* GENERATED by scripts/gen-static.mjs — do not edit.
       * GitHub Pages has no rewrites, so a cold load of a deep link would 404 before
       * the SPA boots. Stash the path, bounce to the shell; src/main.tsx replays it. */
      (function () {
        var BASE = ${JSON.stringify(BASE)};
        var p = window.location.pathname;
        if (p.indexOf(BASE) === 0 && p !== BASE) {
          try { sessionStorage.setItem("ph:redirect", p + window.location.search + window.location.hash); } catch (e) {}
          window.location.replace(BASE + "index.html");
        }
      })();
    </script>
  </head>
  <body></body>
</html>
`,
);
console.log(`static: base ${BASE} · ${paths.length} sitemap URLs · ${SITE}`);
